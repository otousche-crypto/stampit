/**
 * Generates the home page demo: the real generateHtml() output for the demo
 * config (§9.3), injected as-is by the home page.
 */
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { DEMO_CONFIG } from '../src/badge/demo'
import { badgeConfigSchema } from '../src/badge/schema'
import { generateHtml } from '../src/badge/export/generateHtml'

const config = badgeConfigSchema.parse(DEMO_CONFIG)
const html = generateHtml(config)
const out = fileURLToPath(new URL('../src/app/demo.generated.ts', import.meta.url))
writeFileSync(
  out,
  `// Generated by scripts/build-demo.ts. Do not edit.\nexport const DEMO_MODE = ${JSON.stringify(config.click.mode)} as "link" | "bubbles"\nexport const DEMO_HTML = ${JSON.stringify(html)}\n`,
)
console.log(`demo badge: ${html.length} bytes`)
