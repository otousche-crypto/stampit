/**
 * Generates the home page demo: the real generateHtml() output for the demo
 * config (§9.3), injected as-is by the home page.
 */
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { DEMO_CONFIG } from '../src/badge/demo'
import { badgeConfigSchema } from '../src/badge/schema'
import { generateHtml } from '../src/badge/export/generateHtml'

const config = badgeConfigSchema.parse(DEMO_CONFIG)
// The site's Light / Dark is a class, not the OS setting: one snippet per scheme.
const light = generateHtml(config, { previewScheme: 'light' })
const dark = generateHtml(config, { previewScheme: 'dark' })
const out = fileURLToPath(new URL('../src/app/demo.generated.ts', import.meta.url))
writeFileSync(
  out,
  `// Generated by scripts/build-demo.ts. Do not edit.\nexport const DEMO_HTML_LIGHT = ${JSON.stringify(light)}\nexport const DEMO_HTML_DARK = ${JSON.stringify(dark)}\n`,
)
console.log(`demo badge: ${light.length} bytes`)
