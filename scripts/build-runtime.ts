/** Minifies src/badge/export/runtime.source.js into runtime.generated.ts. */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { minifyRuntime } from '../src/badge/export/minify-runtime'

const dir = fileURLToPath(new URL('../src/badge/export/', import.meta.url))
const source = readFileSync(dir + 'runtime.source.js', 'utf8')
const code = await minifyRuntime(source)
writeFileSync(
  dir + 'runtime.generated.ts',
  `// Generated by scripts/build-runtime.ts from runtime.source.js. Do not edit.\nexport const RUNTIME_MIN = ${JSON.stringify(code)}\n`,
)
console.log(`runtime: ${code.length} bytes`)
